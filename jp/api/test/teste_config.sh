#!/usr/bin/env bash
# =============================================================================
# teste_config.sh — ★ ここを記入する。編集するのはこのファイルだけ。
#
# `preparar_teste.sh` がこの値を読み込み、.mp4 を探してテストのロールを
# 組み立てる。`teste_manual.sh` はそれを使って各組み合わせを実行する。
# =============================================================================


# ─────────────────────────────────────────────────────────────────────────────
# 1. API の所在
# ─────────────────────────────────────────────────────────────────────────────
API_HOST="localhost"
API_PORT="8000"
API_SCHEME="http"


# ─────────────────────────────────────────────────────────────────────────────
# 2. シーン  —  ★ 次の 2 つのモードのどちらかを選ぶ
# ─────────────────────────────────────────────────────────────────────────────
#
#   モード A — 宣言（推奨。常に動作する唯一のモード）
#            シーンを自分で指定する。ディスクからは何も読まない。
#            curl を手で組み立てるのと同等。
#
#   モード B — 探索
#            スクリプトが .mp4 を列挙する。ホスト（または docker exec 経由で
#            コンテナ）からディレクトリを読めることが前提。
#
# CENAS_A が記入されていればモード A が優先され、それ以外は無視される。
# ─────────────────────────────────────────────────────────────────────────────

# `scene_video_path` に入るプレフィックス — API から見たパス。
# Docker では bind-mount のマウント先（`volumes:` の右側）。
BASE_API="/dados/cenas"

# program_id — RefCap では `collection` になる
PROGRAM_ID="prog_teste"


# ── モード A: シーンを宣言する ─────────────────────────────────────────────
#
# パスは次のように組み立てられる:
#     $BASE_API/$PROGRAM_ID/$VIDEO_A/<シーン>.mp4
#
# ★ グルーピング（別ディレクトリのシーンは別々の build になる）を検証するには、
#   VIDEO_B に 2 つ目のディレクトリを記入する。未記入なら、このテストは
#   スキップされる。

VIDEO_A="vidA"
CENAS_A="cena_01 cena_02 cena_03"

VIDEO_B=""
CENAS_B=""

# 1 秒未満のシーンがあれば、viddataset のパッチを検証するためにここに記入する。
# なければ空のまま。
CENA_CURTA=""
CENA_CURTA_VIDEO=""

# ファイルの拡張子
EXT=".mp4"


# ── モード B: 探索（CENAS_A が空の場合のみ） ──────────────────────────────
#
# BASE_HOST  スクリプトがホスト上で .mp4 を探す場所
# CONTAINER  記入されていれば、ホストを読む代わりに `docker exec` で列挙する

BASE_HOST=""

# CONTAINER には 2 種類の値を指定できる — どちらかはスクリプトが判別する:
#
#   コンテナ名  （例: "projeto-caption-api-1"）
#       ★ 推奨: `docker exec` は docker-compose.yml が手元になくても、
#         どのディレクトリからでも動く。
#         確認方法:  docker ps --format '{{.Names}}'
#
#   サービス名  （例: "caption-api"）
#       docker-compose.yml が必要 — その場所を COMPOSE_FILE に指定する。
CONTAINER=""

# CONTAINER がサービス名で、かつスクリプトを実行するディレクトリに
# docker-compose.yml がない場合にのみ必要。
#   例: "../../.docker/docker-compose.yml"
COMPOSE_FILE=""

VIDEO_IDS=""          # 空 = すべてのサブディレクトリ


# 3. 2 つ目の番組 — 分離テスト用
#
# 同じ `scene_id` でも番組が異なればキャッシュを共有しないことを証明する。
# 空のままなら、このテストはスキップされる。
# ─────────────────────────────────────────────────────────────────────────────
PROGRAM_ID_2=""
VIDEO_ID_2=""


# ─────────────────────────────────────────────────────────────────────────────
# 4. テストの調整
# ─────────────────────────────────────────────────────────────────────────────

# 使用するシーン数の上限（0 = 見つかったものすべて）。
# ★ 実モデルでは 1 シーンに数秒かかる。まずは 4〜5 から始める。
MAX_CENAS=6

# 各リクエストのタイムアウト（秒）。
TIMEOUT=900

# サービス側で設定された非同期のしきい値（REFCAP_LIMIAR_ASSINCRONO）。
# 手持ちのシーンでこれを超えられる場合にのみ、非同期モードのテストを
# 実行する。デフォルトの 30 では、おそらくスキップされる。
LIMIAR_ASSINCRONO=30
